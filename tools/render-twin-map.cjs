// Renders tools/twin-map.json as docs/TWIN-MAP.md: every question slot of the Chem/Phys diagnostic and the six daily
// quizzes, with its twin card, category, discipline, skill and difficulty, and the mix
// of each set against its target. Run: node tools/render-twin-map.cjs
'use strict';
const fs = require('node:fs');
const S = require('./twin-sources.cjs');
const map = JSON.parse(fs.readFileSync(__dirname + '/twin-map.json', 'utf8'));
const DISC = { gen_chem: 'GCH', biochemistry: 'BCH', physics: 'PHY', organic_chem: 'OCH', biology: 'BIO' };
const SK = { 'SIRS 1': 'S1', 'SIRS 2': 'S2', 'SIRS 3': 'S3', 'SIRS 4': 'S4' };
const TITLE = { diag: 'Diagnostic (59): P P [4] P P P [4] P P P [4] P P [3]' };
for (let i = 1; i <= 6; i++) TITLE['quiz' + i] = 'Daily quiz ' + i + ' (30): P P [4] P P P [4]';
const tally = (rows, k) => { const o = {}; rows.forEach(r => { o[r[k]] = (o[r[k]] || 0) + 1; }); return o; };
const fmt = (got, want, short = x => x) => Object.keys(want).map(k => short(k) + ' ' + (got[k] || 0) + (got[k] === want[k] || (!got[k] && !want[k]) ? '' : ' (target ' + want[k] + ')')).join(', ');

const out = ['# Twin map — Chem/Phys diagnostic and daily quizzes', '',
  'Generated by `tools/solve-twin-map.py` from `tools/twin-clusters.json`; rendered by `tools/render-twin-map.cjs`.',
  'Each row is one question slot. **Twin** is the studied card the question copies the method of (`src` of the card).',
  'Each passage twins the cards of one AAMC passage (question ranges verified against the AAMC review screens). Stand-alones twin AAMC stand-alone cards, or a secondary card where noted.', ''];
const all = [];
for (const set of S.SETS) {
  const m = map.sets[set.id], rows = [];
  const lay = set.layout;
  let p = 0, sa = 0;
  const body = ['| Slot | Twin | AAMC passage | Cat | Disc | Skill | Diff |', '|---|---|---|---|---|---|---|'];
  for (const step of lay) {
    if (step === 'P') { const g = m.passages[p++];
      g.rows.forEach((r, i) => { const slot = (set.id === 'diag' ? 'D' : 'Q' + set.id.slice(4)) + '-P' + p + '.' + (i + 1); rows.push(r);
        body.push(`| ${slot} | \`${r.twin}\` | ${g.cluster} | ${r.aamc} | ${DISC[r.disc]} | ${SK[r.skill]} | ${r.diff} |`); }); }
    else for (let k = 0; k < step; k++) { const r = m.standalones[sa++], slot = (set.id === 'diag' ? 'D' : 'Q' + set.id.slice(4)) + '-SA' + sa; rows.push(r);
      body.push(`| ${slot} | \`${r.twin}\` | ${r.twin.includes('-cp:') ? 'stand-alone' : 'stand-alone (secondary card)'} | ${r.aamc} | ${DISC[r.disc]} | ${SK[r.skill]} | ${r.diff} |`); }
  }
  all.push(...rows);
  const t = set.t;
  out.push('## ' + TITLE[set.id], '',
    '- Categories: ' + fmt(tally(rows, 'aamc'), t.cats),
    '- Disciplines: ' + fmt(tally(rows, 'disc'), t.discs, k => DISC[k]),
    '- Skills: ' + fmt(tally(rows, 'skill'), t.skills, k => SK[k]),
    '- Difficulty: ' + fmt(tally(rows, 'diff'), t.diffs),
    '- Draw by source: ' + Object.entries(tally(rows.map(r => ({ e: r.twin.includes('-cp:') ? r.twin.split(':')[0] : 'secondary' })), 'e')).sort().map(([k, v]) => k + ' ' + v).join(', '), '', ...body, '');
}
const ids = all.map(r => r.twin);
out.splice(5, 0, `**${ids.length} slots, ${new Set(ids).size} distinct twins** (no card twinned twice). Practice Exam / Sample Test cards: ${ids.filter(i => i.includes('-cp:')).length}; secondary cards (stand-alones only): ${ids.filter(i => !i.includes('-cp:')).length}.`, '');
fs.writeFileSync(__dirname + '/../docs/TWIN-MAP.md', out.join('\n'));
console.log('docs/TWIN-MAP.md: ' + ids.length + ' slots, ' + new Set(ids).size + ' distinct');
